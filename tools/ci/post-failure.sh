#!/usr/bin/env bash
# One comment per workflow on the PR: the failing lines of the run, or "green again".
# Needs GH_TOKEN, RUN_ID, RUN_URL, WORKFLOW, CONCLUSION, PR, SHA and GITHUB_REPOSITORY.
set -euo pipefail

marker="<!-- ci-summary:${WORKFLOW} -->"
api="repos/${GITHUB_REPOSITORY}/issues"
id=$(gh api "${api}/${PR}/comments" --paginate \
  --jq ".[] | select(.body | contains(\"${marker}\")) | .id" | head -1)

if [ "$CONCLUSION" = success ]; then
  [ -n "$id" ] || exit 0
  body="${marker}
**${WORKFLOW}**: green on \`${SHA:0:7}\`."
else
  # Log text is untrusted: no backticks to break the fence, no @mentions to notify anyone.
  lines=$(gh run view "$RUN_ID" --repo "$GITHUB_REPOSITORY" --log-failed 2>/dev/null \
    | bash tools/ci/failure-lines.sh | sed 's/`/'"'"'/g; s/@/@\xe2\x80\x8b/g')
  body="${marker}
**${WORKFLOW}** failed on \`${SHA:0:7}\` ([run](${RUN_URL})):

\`\`\`
${lines:-no failing lines found, open the run}
\`\`\`"
fi
body="${body}

---
_Generated by [Claude Code](https://claude.ai/code)_"

if [ -n "$id" ]; then
  gh api -X PATCH "${api}/comments/${id}" -f body="$body" >/dev/null
else
  gh api "${api}/${PR}/comments" -f body="$body" >/dev/null
fi
