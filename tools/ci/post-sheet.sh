#!/usr/bin/env bash
# Pushes shots/sheet.jpg to the ci-shots branch and puts it in one updated comment on the PR.
# Needs GH_TOKEN, PR, SHA and GITHUB_REPOSITORY (set by the workflow).
set -euo pipefail

file="sheet-${SHA:0:7}.jpg"
git config user.name github-actions
git config user.email actions@github.com
if git ls-remote --exit-code --heads origin ci-shots >/dev/null; then
  git fetch -q origin ci-shots
  git worktree add -q ../ci-shots ci-shots
else
  git worktree add -q --orphan -b ci-shots ../ci-shots
fi
cd ../ci-shots
mkdir -p "pr-$PR"
rm -f "pr-$PR"/sheet-*.jpg
cp "$OLDPWD/shots/sheet.jpg" "pr-$PR/$file"
git add .
git commit -qm "Sheet of PR $PR at ${SHA:0:7}"
git push -q origin HEAD:ci-shots

marker='<!-- ci-sheet -->'
url="https://raw.githubusercontent.com/${GITHUB_REPOSITORY}/ci-shots/pr-${PR}/${file}"
body="${marker}
**Screenshot sheet** of \`${SHA:0:7}\`: sea day (desktop, phone), sea night, Saltmere market (desktop, phone) and the chart.

![sheet](${url})

---
_Generated by [Claude Code](https://claude.ai/code)_"
id=$(gh api "repos/${GITHUB_REPOSITORY}/issues/${PR}/comments" --paginate \
  --jq ".[] | select(.body | contains(\"${marker}\")) | .id" | head -1)
if [ -n "$id" ]; then
  gh api -X PATCH "repos/${GITHUB_REPOSITORY}/issues/comments/${id}" -f body="$body" >/dev/null
else
  gh api "repos/${GITHUB_REPOSITORY}/issues/${PR}/comments" -f body="$body" >/dev/null
fi
