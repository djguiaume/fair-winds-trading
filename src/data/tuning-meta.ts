/** Objects whose keys are ids: their children are written `*` in meta paths. */
export const ID_COLLECTIONS: readonly string[] = [
  'ships',
  'goods',
  'difficulty.levels',
  'weather.default.kinds',
  'weather.zones.kinds',
  'economy.towns.growthToLevel',
  'upgrades.homePortLevel',
];

/** The meta path of a value: `['ships', 'cutter', 'hold']` → `ships.*.hold`. */
export function metaPath(path: readonly string[]): string {
  const out: string[] = [];
  for (const key of path) {
    out.push(ID_COLLECTIONS.includes(out.join('.')) ? '*' : key);
  }
  return out.join('.');
}

const num = (
  label: string,
  min: number,
  max: number,
  step: number,
  unit: string | undefined,
  help: string,
): NumberMeta => ({ kind: 'number', label, min, max, step, ...(unit ? { unit } : {}), help });
const text = (label: string, help: string): TextMeta => ({ kind: 'text', label, help });
const toggle = (label: string, help: string): ToggleMeta => ({ kind: 'toggle', label, help });

