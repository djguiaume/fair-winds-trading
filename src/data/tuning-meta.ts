/**
 * What every tuning value means (decision 0094): a label, a range, a step, a unit and one line of
 * help, keyed by its path in `TUNING`. Ids in a collection (ship classes, goods, difficulty levels,
 * weather kinds, town and upgrade levels) are written `*`, so one entry covers every ship. The
 * `?tune` panel builds its sliders from this file, and a test checks that every value in
 * `src/data/tuning/*.json` has an entry and sits inside its range: a new value needs a line here.
 */

/** A number, or a list of numbers that share one range (each element is checked). */
export interface NumberMeta {
  kind: 'number';
  label: string;
  min: number;
  max: number;
  step: number;
  unit?: string;
  help: string;
}

/** A polar curve: [true wind angle 0..180°, fraction of top speed 0..1] points. */
export interface PolarMeta {
  kind: 'polar';
  label: string;
  help: string;
}

export interface ToggleMeta {
  kind: 'toggle';
  label: string;
  help: string;
}

/** Names, icons and ids: shown but not slid. */
export interface TextMeta {
  kind: 'text';
  label: string;
  help: string;
}

export type TuningMeta = NumberMeta | PolarMeta | ToggleMeta | TextMeta;

/** Tabs of the panel, one per tuning file. */
